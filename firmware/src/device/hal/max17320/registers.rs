//! Internal 9-bit register addresses, local Rev. 12 Tables 90–93 and 106.
//! AtAvSOC follows Table92 (0DEh); the p.122 heading appears to typo it as 0CEh.

/// Raw internal word address. Addresses 100h–17Fh use SBS/word transfers, with
/// special block semantics at six commands; 180h–1FFh are shadow/history RAM.
/// Reserved locations have undefined data and must not be written. `new` only
/// checks the address width, so raw users must check the selected silicon map.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct Register(u16);

impl Register {
    pub const fn new(address: u16) -> Option<Self> {
        if address <= 0x1ff {
            Some(Self(address))
        } else {
            None
        }
    }
    pub const fn address(self) -> u16 {
        self.0
    }
    pub const fn bus_address(self) -> u8 {
        if self.0 < 0x100 { 0x36 } else { 0x0b }
    }
    pub const fn command_byte(self) -> u8 {
        self.0 as u8
    }
    pub const fn is_sbs(self) -> bool {
        self.0 >= 0x100 && self.0 < 0x180
    }
    pub const fn is_sbs_block(self) -> bool {
        matches!(self.0, 0x11c | 0x120 | 0x121 | 0x122 | 0x123 | 0x170)
    }
    pub const fn is_shadow(self) -> bool {
        self.0 >= 0x180 && self.0 <= 0x1ef
    }
    pub const fn shadow_writable(self) -> bool {
        self.is_shadow() && !matches!(self.0, 0x1bc..=0x1c1 | 0x1cb | 0x1e4 | 0x1e5)
    }
    pub const fn x_table(index: u8) -> Option<Self> {
        if index < 12 {
            Some(Self(0x180 + index as u16))
        } else {
            None
        }
    }
    pub const fn ocv_table(index: u8) -> Option<Self> {
        if index < 12 {
            Some(Self(0x190 + index as u16))
        } else {
            None
        }
    }
    pub const fn sha_word(index: u8) -> Option<Self> {
        if index < 16 {
            Some(Self(0x0c0 + index as u16))
        } else {
            None
        }
    }
    pub const fn history_word(index: u8) -> Option<Self> {
        if index < 16 {
            Some(Self(0x1f0 + index as u16))
        } else {
            None
        }
    }
}

macro_rules! registers {
    ($($name:ident = $address:literal),* $(,)?) => {
        impl Register { $(pub const $name: Self = Self($address);)* }
    };
}
